import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
import { MCP_TOOLS } from "../src/lib/agent-contract";

/** Read public literals without importing the hosted transport's server-only graph. */
export async function generateContract(root = process.cwd()) {
  const source = ts.createSourceFile("agent-transport.ts", await readFile(resolve(root, "src/lib/agent-transport.ts"), "utf8"), ts.ScriptTarget.Latest, true);
  const literal = (node: ts.Expression): string | number | (string | number)[] => {
    if (ts.isStringLiteral(node)) return node.text;
    if (ts.isNumericLiteral(node)) return Number(node.text);
    if (ts.isArrayLiteralExpression(node)) return node.elements.map(n => {
      const value = literal(n); if (Array.isArray(value)) throw Error("Expected a flat public literal."); return value;
    });
    throw Error("Public transport constants must be literals; review the contract generator.");
  };
  const read = (name: string) => {
    for (const statement of source.statements) {
      if (!ts.isVariableStatement(statement)) continue;
      for (const declaration of statement.declarationList.declarations) {
        if (ts.isIdentifier(declaration.name) && declaration.name.text === name && declaration.initializer) return literal(declaration.initializer);
      }
    }
    throw Error(`Missing public transport constant: ${name}`);
  };
  const hosted = read("MCP_INSTRUCTIONS");
  const prefix = "Staygreen monitors apps in the workspace selected during Clerk OAuth consent, or the workspace that owns your API token. Every call requires authentication, including initialize. OAuth grants read and write; API tokens can be read-only.";
  if (typeof hosted !== "string" || !hosted.startsWith(prefix)) throw Error("Hosted authentication instructions changed; review the local adaptation.");
  const instructions = "Staygreen monitors apps in the workspace that owns your STAYGREEN_API_TOKEN. Create a read-only or read-and-write workspace API token at /app/agents. initialize, ping and tools/list need no token. Every tools/call requires a token except scan_app, which uses the public scan service when no token is set. This local server does not use OAuth." + hosted.slice(prefix.length);
  return JSON.stringify({
    _generated: "Generated by npm run cli:contract from the public hosted contract. Do not edit by hand.",
    versions: read("MCP_VERSIONS"), lineLimit: read("BODY_LIMIT"), instructions, tools: MCP_TOOLS,
  }, null, 2) + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await writeFile(resolve("packages/staygreen/src/contract.generated.json"), await generateContract());
}
