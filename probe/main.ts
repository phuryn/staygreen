import "./threadpool";
import { Probe } from "./runtime";
import { Store } from "./store";
import { Canary } from "./canary";
import { ConfigError, parseConfig, runtimeSchema } from "./env";

/* The probe as a process: `node probe/dist/main.js`, configured by environment.

     DATABASE_URL         Postgres, as this probe's own role, a member of `probe` (`docs/environments.md`, Probes)
     PROBE_ID             a short id, unique across the fleet (`tor1-a`)
     PROBE_LOCATION       tor1 | sfo3 | fra1, the droplet's region (`locations` in src/lib/plans.ts)
     PROBE_BUILDER_ONLY   "true" for the box Free monitors aren't checked from
     PROBE_URL            how the other probes reach this one (`http://10.0.0.2:7070`)
     PROBE_PORT           where it listens (default 7070)
     PROBE_PEER_SECRET    the HMAC secret every probe shares, at least 32 characters
     CREDENTIALS_KEY      the dashboard's key, which opens the monitors' secret headers
     PROBE_RELEASE        SHA-256 of the deployed bundle, generated by the deploy command
     PROBE_WORKSPACES     optional: comma-separated workspace ids, the only ones checked (development) */

async function main() {
  const e = parseConfig(runtimeSchema, process.env, "probe");
  const workspaces = e.PROBE_WORKSPACES?.split(",").map((w) => w.trim()).filter(Boolean);
  const store = Store.connect(e.DATABASE_URL, Buffer.from(e.CREDENTIALS_KEY, "base64url"), workspaces?.length ? workspaces : undefined, e.PROBE_ID);
  const probe = new Probe({
    self: { id: e.PROBE_ID, location: e.PROBE_LOCATION, builderOnly: e.PROBE_BUILDER_ONLY === "true", url: e.PROBE_URL },
    secret: e.PROBE_PEER_SECRET,
    store,
    port: e.PROBE_PORT,
    release: e.PROBE_RELEASE,
    canary: new Canary(),
  });
  await probe.start();
  await probe.flush();
  console.log(JSON.stringify({ msg: "probe started", ...probe.health() }));

  const stop = async () => {
    await probe.stop();
    await store.close();
    process.exit(0);
  };
  process.once("SIGTERM", stop);
  process.once("SIGINT", stop);
  setInterval(() => console.log(JSON.stringify({ msg: "probe", ...probe.health(), ...probe.counts })), 60_000).unref();
}

main().catch((err) => {
  // Database and network exceptions can contain connection strings or credentials.
  console.error(err instanceof ConfigError ? err.message : "probe failed to start; check database functions and connectivity");
  process.exit(1);
});
